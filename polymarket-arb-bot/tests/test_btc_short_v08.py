def _make_5m_or_15m_event(asset: str, dur: str, start_ts: int, ptb: float | None = None, fp: float | None = None, tick: float = 0.01):
    end_ts = start_ts + (300 if dur == "5m" else 900)
    raw = {
        "id": f"ev_{asset}_{dur}_{start_ts}",
        "slug": f"{asset}-updown-{dur}-{start_ts}",
        "title": f"{asset.upper()} Up or Down - {dur} {start_ts}",
        "startTime": datetime.fromtimestamp(start_ts, timezone.utc).isoformat(),
        "endDate": datetime.fromtimestamp(end_ts, timezone.utc).isoformat(),
        "seriesSlug": f"{asset}-up-or-down-{dur}",
        "eventMetadata": {
            **({"priceToBeat": ptb} if ptb is not None else {}),
            **({"finalPrice": fp} if fp is not None else {}),
        },
        "markets": [
            {
                "id": f"m_{asset}_{dur}_{start_ts}",
                "conditionId": "0x" + "12" * 32,
                "question": f"{asset.upper()} Up or Down",
                "slug": f"{asset}-updown-{dur}-{start_ts}",
                "clobTokenIds": [f"U_{asset}_{dur}_{start_ts}", f"D_{asset}_{dur}_{start_ts}"],
                "outcomes": ["Up", "Down"],
                "active": True,
                "closed": False,
                "acceptingOrders": True,
                "orderPriceMinTickSize": tick,
                "orderMinSize": 5,
                "eventStartTime": datetime.fromtimestamp(start_ts, timezone.utc).isoformat(),
                "endDate": datetime.fromtimestamp(end_ts, timezone.utc).isoformat(),
                "feeSchedule": {"rate": 0.07, "exponent": 1.0, "takerOnly": True, "rebateRate": 0.20},
                "cryptoMarketConfig": {"asset": asset, "duration": dur, "twapEnabled": True, "twapLookbackSeconds": 60},
                "description": DESC_TWAP.replace("btc", asset),
            }
        ],
    }
    return parse_event(raw)


# ---------------------------------------------------------------- Pillar 1: Post-Close 100% Zero-Risk Lock + 0.99 Bonding


async def test_post_close_5m_zero_risk_maker_bonding_and_fast_paper_redeem(store, tmp_path):
    """Exact reproduction of on-chain BTC 5m post-close fills (e.g. 20,093 shares @ 0.99 in [+1s..+35s]):
    1. Cold-start seeds exact S_open from preceding 5m window's finalPrice (68,801.6388).
    2. At T_end (1794562200), Chainlink RTDS emits 68,780.10 (< S_open => Down is 100% locked!).
    3. Orderbook has empty Down asks (YES/Up bids = []) and resting Down bid @ 0.99 (Up ask = 0.01).
    4. MakerArbManager posts 0-fee postOnly BUY Down @ 0.99 (+1.01% + Maker Rebate, 0 hedge legs!),
       fills when retail dumps, and LifecycleManager auto-redeems $1.00/sh in paper mode within 12s!
    """
    t0 = 1794561900
    t_end = t0 + 300
    prev_raw = {
        "id": "ev_prev",
        "slug": f"btc-updown-5m-{t0 - 300}",
        "title": "BTC prev 5m",
        "endDate": datetime.fromtimestamp(t0, timezone.utc).isoformat(),
        "eventMetadata": {"priceToBeat": 68806.77, "finalPrice": 68801.6388},
        "markets": [
            {
                "id": "m_prev",
                "clobTokenIds": ["up_p", "dn_p"],
                "outcomes": ["Up", "Down"],
                "active": False,
                "closed": True,
                "acceptingOrders": False,
                "outcomePrices": ["0", "1"],
                "description": DESC_TWAP,
            }
        ],
    }
    cur_ev = _make_5m_or_15m_event("btc", "5m", t0, ptb=None, tick=0.01)

    rtds = ChainlinkRtdsFeed()
    # Verify cold-start benchmark seeding via fetch_short_crypto_events!
    def mock_gamma(req: httpx.Request) -> httpx.Response:
        sl = req.url.params.get("slug", "")
        if sl == f"btc-updown-5m-{t0 - 300}":
            return httpx.Response(200, json=[prev_raw])
        if sl == cur_ev.slug:
            return httpx.Response(200, json=[{
                "id": cur_ev.id, "slug": cur_ev.slug, "title": cur_ev.title,
                "startTime": datetime.fromtimestamp(t0, timezone.utc).isoformat(),
                "endDate": datetime.fromtimestamp(t_end, timezone.utc).isoformat(),
                "markets": [{
                    "id": cur_ev.markets[0].id, "clobTokenIds": [cur_ev.markets[0].yes_token, cur_ev.markets[0].no_token],
                    "outcomes": ["Up", "Down"], "active": True, "closed": False, "acceptingOrders": True,
                    "orderPriceMinTickSize": 0.01, "orderMinSize": 5, "description": DESC_TWAP,
                }],
            }])
        return httpx.Response(200, json=[])

    async with httpx.AsyncClient(transport=httpx.MockTransport(mock_gamma)) as http:
        evs = await fetch_short_crypto_events(http, rtds_feed=rtds, now=t0 + 10)
    assert len(evs) == 1
    assert rtds.twap_at("btc", t0) == pytest.approx(68801.6388)

    # At t = t_end, RTDS emits exact closing 60s-TWAP = 68,780.10 (< 68,801.6388 => Down = Outcome.NO wins!)
    rtds.ingest_message({
        "topic": "crypto_prices_twap_sixty",
        "payload": {"symbol": "btc/usd", "timestamp": t_end * 1000, "value": 68780.10},
    })

    # Book has Up bids = [] (Down asks = []) and Up asks = [(0.01, 800)] (Down bids = [(0.99, 800)])
    mkt = cur_ev.markets[0]
    store.put(book(mkt.yes_token, bids=[], asks=[(0.01, 800.0)]))

    cfg = Config()
    cfg.risk.kill_file = ""
    cfg.risk.bankroll_usd = 70.0
    cfg.risk.max_trade_usd = 25.0
    all_strats = build_all_strategies(cfg, rtds_feed=rtds)
    strat_map = {s.name: s for s in all_strats}
    u = build_universe([cur_ev], all_strats, cfg.universe)

    gw = PaperGateway(store)
    risk = RiskManager(cfg.risk, tmp_path / "state.json")
    journal = Journal(tmp_path / "journal.jsonl")
    maker = MakerArbManager(cfg, store, gw, risk, journal, strategies=strat_map)
    maker.set_targets(u.targets)

    cands = maker.find_candidates(now=t_end + 2.0)
    assert len(cands) == 1
    plan = cands[0]
    assert plan.strategy == "maker_crypto_short"
    assert plan.lead_outcome is Outcome.NO  # Down!
    assert plan.lead_price == pytest.approx(0.99)
    assert plan.hedge_legs == [] and plan.profit > 0.24

    # Place & simulate post-close retail seller dumping Down @ 0.99 (buying Up @ 0.01)
    res = await gw.place_limit(mkt.no_token, Outcome.NO, mkt.yes_token, side=plan.lead_market.outcomes and __import__("polyarb.models", fromlist=["Side"]).Side.BUY, price=0.99, shares=plan.shares, tick=0.01, post_only=True)
    assert res.ok
    from polyarb.execution.maker_arb import ActiveQuote
    maker.active[cur_ev.id] = ActiveQuote(cur_ev.id, res.order_id, plan, plan.total_cost, t_end + 2.0)
    gw._orders[res.order_id].placed_at = t_end + 1.0
    gw.on_market_trade(mkt.yes_token, 0.01, 100.0, now=t_end + 5.0)
    await maker._check_active(cur_ev.id, maker.active[cur_ev.id], t_end + 5.0)

    assert len(risk.state.holds) == 1
    assert risk.state.holds[0].strategy == "maker_crypto_short"

    # 60s later Gamma marks Down winner ["0", "1"] -> LifecycleManager redeems in 12s fast path!
    resolved_payload = {
        "id": cur_ev.id, "title": cur_ev.title,
        "markets": [{"id": mkt.id, "clobTokenIds": [mkt.yes_token, mkt.no_token], "outcomes": ["Up", "Down"], "closed": True, "acceptingOrders": False, "outcomePrices": ["0", "1"]}],
    }
    lc = LifecycleManager(
        cfg, gw, risk, journal, store=store,
        http=httpx.AsyncClient(transport=httpx.MockTransport(lambda r: httpx.Response(200, json=resolved_payload))),
    )
    lc._last_paper_redeem_at = 0.0
    await lc.step()
    assert risk.state.holds == []
    assert risk.state.realized_total == pytest.approx(plan.shares * 0.01)


# ---------------------------------------------------------------- Pillar 2: Exact-Integral Pre-Close 60s-TWAP Lock + Safety Cancel


async def test_integral_twap_lock_requires_90bp_shock_survival_and_cancels_quote_if_eroded(store, tmp_path):
    t0 = 1794561900
    t_end = t0 + 300
    now_s = float(t_end - 8)  # 8 seconds left! 52 of 60 seconds ALREADY realized!
    ev = _make_5m_or_15m_event("btc", "5m", t0, ptb=68700.0, tick=0.01)
    mkt = ev.markets[0]

    rtds = ChainlinkRtdsFeed()
    # Seed 52 seconds [t_end-60 .. t_end-8] at $68,850 (+21.8 bps above 68,700 -> survives 90 bps shock over 8s easily!)
    for s in range(t_end - 60, int(now_s) + 1):
        rtds._cl_spot_sec["btc"][s] = 68850.0
    rtds._latest_cl_spot["btc"] = (int(now_s), 68850.0)
    rtds._latest_twap["btc"] = (int(now_s), 68850.0)
    rtds._latest_bin_spot["btc"] = (int(now_s), 68852.0)

    # Stale Up ask at 0.94 -> Taker snipes immediately!
    store.put(book(mkt.yes_token, bids=[(0.92, 200)], asks=[(0.94, 50)]))
    strat = CryptoShortArb(CryptoShortConfig(shock_bps=90.0), rtds_feed=rtds, max_trade_usd=25.0)
    (target,) = strat.targets([ev])
    (opp,) = strat.evaluate(target, store, now_s)
    assert opp.meta["mode"] == "integral_twap_lock"
    assert opp.legs[0].outcome is Outcome.YES  # Up!
    assert opp.profit > 1.0

    # If Binance spot suddenly flash-crashes -40 bps ahead of Chainlink, Binance lead-lag guard blocks entry!
    rtds._latest_bin_spot["btc"] = (int(now_s), 68500.0)
    assert strat.evaluate(target, store, now_s) == []
    assert strat.still_safely_locked(target, Outcome.YES, now_s) is False


# ---------------------------------------------------------------- Pillar 3: 5m <-> 15m Same-Chainlink-Stream Synchronized Lock


def test_sync_5m_15m_same_chainlink_stream_zero_basis_double_payout_lock(store):
    t15 = 1794561300
    t5 = t15 + 600  # 3rd 5m sub-window [1794561900 .. 1794562200], exact same end_ts!

    ev15 = _make_5m_or_15m_event("btc", "15m", t15, ptb=68750.0, tick=0.01)
    ev5 = _make_5m_or_15m_event("btc", "5m", t5, ptb=68810.0, tick=0.01)

    # S_5 (68,810) > S_15 (68,750) => Lock is Down_5 + Up_15!
    # Suppose 5m Up bid = 0.56 => Down_5 ask = 0.44; 15m Up ask = 0.52 => 0.44 + 0.52 + fees < 1.00!
    store.put(book(ev5.markets[0].yes_token, bids=[(0.56, 100)], asks=[(0.58, 100)]))
    store.put(book(ev15.markets[0].yes_token, bids=[(0.50, 100)], asks=[(0.52, 100)]))

    strat = CryptoShortArb(CryptoShortConfig(min_profit_usd=0.10, min_edge=0.004), max_trade_usd=25.0)
    targets = strat.targets([ev15, ev5])
    sync_t = next(t for t in targets if t.key.startswith("csync:"))
    (opp,) = strat.evaluate(sync_t, store, float(t5 + 30))

    assert opp.meta["mode"] == "sync_5m_15m"
    assert [(leg.market_id, leg.outcome) for leg in opp.legs] == [
        (ev5.markets[0].id, Outcome.NO),
        (ev15.markets[0].id, Outcome.YES),
    ]
    assert opp.profit > 0.12
    assert opp.profit == pytest.approx(opp.shares * (1.0 - (0.44 + 0.07 * 0.44 * 0.56 + 0.52 + 0.07 * 0.52 * 0.48)))

    # Verify payoff >= $1.00 for EVERY possible settling Chainlink TWAP X_end, and $2.00 in [68750, 68810)!
    for x_end in (68600.0, 68750.0, 68780.0, 68810.0, 69000.0):
        down_5 = 1.0 if x_end < 68810.0 else 0.0
        up_15 = 1.0 if x_end >= 68750.0 else 0.0
        assert down_5 + up_15 >= 1.0
        if 68750.0 <= x_end < 68810.0:
            assert down_5 + up_15 == 2.0


