    store.put(book(m_68800.yes_token, bids=[(0.40, 100)], asks=[(0.45, 100)]))

    b_feed = BinanceFeed(symbols=("BTCUSDT",))
    strat = CryptoShortArb(CryptoShortConfig(min_profit_usd=0.08, min_edge=0.004), binance_feed=b_feed, max_trade_usd=25.0)
    targets = strat.targets([ev_ud, ev_ab])
    anchor_targets = [t for t in targets if t.key.startswith("canchor:")]
    assert len(anchor_targets) == 2

    opps = [o for t in anchor_targets for o in strat.evaluate(t, store, start_dt.timestamp() + 600)]
    assert len(opps) == 1
    assert opps[0].meta["mode"] == "anchor_1h"
    assert [(leg.market_id, leg.outcome) for leg in opps[0].legs] == [("m_ud", Outcome.NO), (m_68600.id, Outcome.YES)]

    # Verify payoff >= $1.00 at every settlement price including exact Open and Strike!
    for c_px in (68500.0, 68600.0, 68650.0, 68717.47, 68900.0):
        dn_1h = 1.0 if c_px < 68717.47 else 0.0
        yes_68600 = 1.0 if c_px > 68600.0 else 0.0
        assert dn_1h + yes_68600 >= 1.0


