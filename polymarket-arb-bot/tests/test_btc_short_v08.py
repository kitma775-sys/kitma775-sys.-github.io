    start_dt = end_dt - timedelta(hours=1)

    ev_ud = parse_event({
        "id": "ev_1h_ud",
        "slug": "bitcoin-up-or-down-november-13-2026-4am-et",
        "title": "Bitcoin Up or Down - November 13, 4AM ET",
        "endDate": end_dt.isoformat(),
        "eventMetadata": {"priceToBeat": 68717.47},
        "markets": [{
            "id": "m_ud", "clobTokenIds": ["u_1h", "d_1h"], "outcomes": ["Up", "Down"],
            "active": True, "closed": False, "acceptingOrders": True,
            "orderPriceMinTickSize": 0.01, "orderMinSize": 5,
            "eventStartTime": start_dt.isoformat(), "endDate": end_dt.isoformat(),
            "feeSchedule": {"rate": 0.07, "exponent": 1.0, "takerOnly": True, "rebateRate": 0.20},
            "description": DESC_1H_UD,
        }],
    })

    m_68600 = make_market("Bitcoin above 68,600 on November 13, 5AM ET?", group="68,600", neg_risk=False, tick=0.001, fee=CRYPTO_FEE, end=end_dt)
    m_68800 = make_market("Bitcoin above 68,800 on November 13, 5AM ET?", group="68,800", neg_risk=False, tick=0.001, fee=CRYPTO_FEE, end=end_dt)
    ev_ab = make_event([m_68600, m_68800], neg_risk=False, title="Bitcoin above ___ on November 13, 5AM ET?")
    ev_ab.end_date = end_dt
    ev_ab.oracle_sig = "binance_1h:btc_usdt"

    # K = 68,600 < Open = 68,717.47 => Down_1h + YES(>68,600) >= $1.00 ($2.00 on (68600, 68717.47))!
    # Price Up_1h bid = 0.68 => Down_1h ask = 0.32; YES(>68,600) ask = 0.64 => 0.32 + 0.64 + fees = 0.991 < 1.00!
    store.put(book("u_1h", bids=[(0.68, 100)], asks=[(0.70, 100)]))
