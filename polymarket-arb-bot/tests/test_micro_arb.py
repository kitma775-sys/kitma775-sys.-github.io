DESC = (
    'This market will resolve to "Up" if the time-weighted average price (TWAP) of Bitcoin, '
    "generated by Chainlink, of the time range specified in the title is greater than or equal "
    "to the price at the beginning of that range. https://data.chain.link/streams/btc-usd-twap-60s-streams."
)


def _event(dur: str, start_ts: int, ptb: float, tick: float = 0.01):
    end_ts = start_ts + (300 if dur == "5m" else 900)
    return parse_event({
        "id": f"ev_{dur}_{start_ts}",
        "slug": f"btc-updown-{dur}-{start_ts}",
        "title": f"BTC Up or Down {dur} {start_ts}",
        "startTime": datetime.fromtimestamp(start_ts, timezone.utc).isoformat(),
        "endDate": datetime.fromtimestamp(end_ts, timezone.utc).isoformat(),
        "seriesSlug": f"btc-up-or-down-{dur}",
        "eventMetadata": {"priceToBeat": ptb},
        "markets": [{
            "id": f"m_{dur}_{start_ts}",
            "conditionId": "0x" + ("ab" if dur == "5m" else "cd") * 32,
            "question": "Bitcoin Up or Down",
            "slug": f"btc-updown-{dur}-{start_ts}",
            "clobTokenIds": [f"U_{dur}_{start_ts}", f"D_{dur}_{start_ts}"],
            "outcomes": ["Up", "Down"],
            "active": True,
            "closed": False,
            "acceptingOrders": True,
            "orderPriceMinTickSize": tick,
            "orderMinSize": 5,
            "eventStartTime": datetime.fromtimestamp(start_ts, timezone.utc).isoformat(),
            "endDate": datetime.fromtimestamp(end_ts, timezone.utc).isoformat(),
            "feeSchedule": {"rate": 0.07, "exponent": 1.0, "takerOnly": True, "rebateRate": 0.20},
            "cryptoMarketConfig": {"asset": "btc", "duration": dur, "twapEnabled": True, "twapLookbackSeconds": 60},
            "description": DESC,
        }],
    })


def _strat(**kwargs) -> MicroArb:
    cfg = MicroArbConfig(**kwargs)
    return MicroArb(cfg, max_trade_usd=40.0)


def test_default_stake_is_ten_dollars_for_the_whole_round():
    cfg = Config().micro_arb
    assert cfg.max_cost_usd == 10.0
    assert cfg.enabled is True
    assert cfg.max_open_rounds == 3
    assert cfg.merge_start_s == 5.0
    assert cfg.merge_window_s == 210.0
    assert cfg.min_strike_gap == 50.0
    assert cfg.tail_last_s == 25.0


def test_merge_buys_both_real_books_and_stops_at_ten_dollars(store):
    start = 1_794_561_900
    ev = _event("5m", start, 70_000.0)
    mkt = ev.markets[0]
    store.put(book(mkt.yes_token, bids=[(0.30, 400)], asks=[(0.40, 400)]))
    store.put(book(mkt.no_token, bids=[(0.30, 400)], asks=[(0.40, 400)]))
    strat = _strat()
    (target,) = [t for t in strat.targets([ev]) if t.key.startswith("micro:")]
    (opp,) = strat.evaluate(target, store, float(start + 30))
    assert opp.meta["mode"] == "micro_merge"
    assert opp.cost <= 10.0 + 1e-6
    assert opp.cost > 8.0
    assert {leg.outcome for leg in opp.legs} == {Outcome.YES, Outcome.NO}
    assert opp.profit > 0.04


