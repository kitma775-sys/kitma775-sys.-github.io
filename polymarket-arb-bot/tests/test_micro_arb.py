def test_corridor_requires_sixty_dollar_gap_and_ten_dollar_cap(store):
    t15 = 1_794_561_300
    t5 = t15 + 600
    wide15 = _event("15m", t15, 75_000.0)
    wide5 = _event("5m", t5, 75_140.0)
    store.put(book(wide5.markets[0].yes_token, bids=[(0.56, 200)], asks=[(0.58, 200)]))
    store.put(book(wide15.markets[0].yes_token, bids=[(0.48, 200)], asks=[(0.50, 200)]))
    strat = _strat()
    sync = next(t for t in strat.targets([wide15, wide5]) if t.key.startswith("micro-sync:"))
    (opp,) = strat.evaluate(sync, store, float(t5 + 30))
    assert opp.meta["mode"] == "micro_corridor"
    assert opp.cost <= 10.0 + 1e-6
    assert [(leg.outcome) for leg in opp.legs] == [Outcome.NO, Outcome.YES]

    near15 = _event("15m", t15, 75_000.0)
    near5 = _event("5m", t5, 75_040.0)
    near = MicroArb(MicroArbConfig(), max_trade_usd=40.0)
    sync_near = next(t for t in near.targets([near15, near5]) if t.key.startswith("micro-sync:"))
    assert near.evaluate(sync_near, store, float(t5 + 30)) == []


def test_tail_lock_needs_two_hundred_eighty_dollars_and_respects_the_ask(store):
    start = 1_794_561_900
    end = start + 300
    now_s = float(end - 12)
    ev = _event("5m", start, 70_000.0)
    mkt = ev.markets[0]
    rtds = ChainlinkRtdsFeed()
    for sec in range(end - 60, int(now_s) + 1):
        rtds._cl_spot_sec["btc"][sec] = 70_320.0
    rtds._latest_cl_spot["btc"] = (int(now_s), 70_320.0)
    rtds._latest_twap["btc"] = (int(now_s), 70_320.0)
    rtds._latest_bin_spot["btc"] = (int(now_s), 70_322.0)
    store.put(book(mkt.yes_token, bids=[(0.97, 80)], asks=[(0.990, 80)]))
    strat = MicroArb(MicroArbConfig(), rtds_feed=rtds, max_trade_usd=40.0)
    (target,) = [t for t in strat.targets([ev]) if t.key.startswith("micro:")]
    (opp,) = strat.evaluate(target, store, now_s)
    assert opp.meta["mode"] == "micro_tail"
    assert opp.legs[0].outcome is Outcome.YES
    assert opp.cost <= 10.0 + 1e-6
    assert opp.meta["reversal_usd"] >= 280

    rtds._cl_spot_sec["btc"].clear()
    for sec in range(end - 60, int(now_s) + 1):
        rtds._cl_spot_sec["btc"][sec] = 70_050.0
    rtds._latest_cl_spot["btc"] = (int(now_s), 70_050.0)
    rtds._latest_twap["btc"] = (int(now_s), 70_050.0)
    assert strat.evaluate(target, store, now_s) == []

    for sec in range(end - 60, int(now_s) + 1):
        rtds._cl_spot_sec["btc"][sec] = 70_320.0
    rtds._latest_cl_spot["btc"] = (int(now_s), 70_320.0)
    store.put(book(mkt.yes_token, bids=[(0.97, 80)], asks=[(0.995, 80)]))
    assert strat.evaluate(target, store, now_s) == []


def test_maker_merge_quotes_only_when_the_real_down_ask_still_fits(store, tmp_path):
    start = 1_794_561_900
    ev = _event("5m", start, 70_000.0)
    mkt = ev.markets[0]
    store.put(book(mkt.yes_token, bids=[(0.50, 200)], asks=[(0.51, 200)]))
    store.put(book(mkt.no_token, bids=[(0.40, 200)], asks=[(0.45, 200)]))
    cfg = Config()
    cfg.risk.kill_file = ""
    cfg.risk.bankroll_usd = 100.0
    strat = MicroArb(cfg.micro_arb, max_trade_usd=cfg.risk.max_trade_usd)
    gw = PaperGateway(store)
    risk = RiskManager(cfg.risk, tmp_path / "state.json")
    maker = MakerArbManager(cfg, store, gw, risk, Journal(tmp_path / "j.jsonl"), strategies={"micro_arb": strat})
    maker.set_targets(strat.targets([ev]))
    plans = maker.find_candidates(now=float(start + 40))
    assert plans and plans[0].strategy == "maker_micro_merge"
    assert plans[0].total_cost <= 10.0 + 1e-6
    assert plans[0].lead_price * plans[0].shares + plans[0].hedge_cost <= plans[0].payout_floor * cfg.micro_arb.merge_max_combined + 1e-6


class _FillAll:
    mode = "paper"

    def __init__(self):
        self.merged: list[tuple[str, float]] = []

    async def buy(self, legs, slippage_ticks=0):
        return [LegResult(leg, True, shares=leg.shares, spent=leg.notional, fee=leg.fee, status="matched") for leg in legs]

    async def merge(self, condition_id, shares):
        self.merged.append((condition_id, shares))
        return True, "paper-merge"


async def test_filled_merge_returns_pusd_instead_of_a_hold(store):
    start = 1_794_561_900
    ev = _event("5m", start, 70_000.0)
    mkt = ev.markets[0]
    store.put(book(mkt.yes_token, bids=[(0.30, 400)], asks=[(0.40, 400)]))
    store.put(book(mkt.no_token, bids=[(0.30, 400)], asks=[(0.40, 400)]))
    strat = _strat()
    (target,) = [t for t in strat.targets([ev]) if t.key.startswith("micro:")]
    (opp,) = strat.evaluate(target, store, float(start + 30))
    gw = _FillAll()
    report = await Executor(gw, store, {"micro_arb": strat}, Config().execution).execute(opp)
    assert report.complete
    assert report.action == "merged both legs to pUSD"
    assert gw.merged and gw.merged[0][0] == mkt.condition_id
    assert report.realized_pnl == pytest.approx(report.proceeds - report.spent)
    assert report.locked_cost == 0


